#!/usr/bin/env python3
"""Write the state a view swaps in and out (#866) into ae3d.vktargets.

A view is a second frame: its own images, framebuffers, history and shadow
atlases. vktargets holds a frame as module variables, so a view is the same
variables with other values, swapped in for the frame it draws and out after.
This reads every `var g_...` of the module, leaves out the ones that are the
device's and the frame's formats (shared by every view) and writes
view_cells / view_save / view_load between the markers in the module.

    python3 scripts/gen_view_swap.py            # rewrite the block
    python3 scripts/gen_view_swap.py --check    # fail when it is not current

tests/test_view_swap checks the same of the checked-in file, in Aether.
"""
import re, sys

MODULE = "src/ae3d/vktargets/module.ae"
BEGIN = "// --- generated by scripts/gen_view_swap.py: the state a view swaps ---"
END = "// --- end of the generated state ---"
# What every view shares with the frame it is beside.
SHARED = [
    "g_color_format", "g_scene_format", "g_color_space", "g_present_mode", "g_depth_format",
    "g_velocity_format", "g_samples", "g_can_capture", "g_cell", "g_view_pass",
    "g_view_read", "g_view_read_bytes",
]

def variables(text):
    out = []
    for line in text.splitlines():
        m = re.match(r"^var (g_[a-z0-9_]+)\s*(?::\s*([a-z]+))?\s*=\s*([^/]*?)\s*(//.*)?$", line)
        if not m:
            continue
        name, kind, init = m.group(1), m.group(2), m.group(3).strip()
        if name in SHARED:
            continue
        if kind is None:
            kind = "bool" if init in ("true", "false") else ("float" if "." in init else "int")
        out.append((name, kind, init))
    return out

def block(vars_):
    lines = [BEGIN,
             "// ${count} variables, 8 bytes each. A view is saved from and loaded into the module's variables.".replace("${count}", str(len(vars_))),
             "const VIEW_CELLS = %d" % len(vars_), "",
             "view_save(cells: ptr) {"]
    for k, (name, kind, init) in enumerate(vars_):
        at = "(cells + %d)" % (k * 8)
        if kind == "ptr":
            lines.append("    (%s as ptr[])[0] = %s" % (at, name))
        elif kind == "bool":
            lines.append("    if %s { (%s as int[])[0] = 1 } else { (%s as int[])[0] = 0 }" % (name, at, at))
        elif kind == "float":
            lines.append("    (%s as float[])[0] = %s" % (at, name))
        else:
            lines.append("    (%s as int[])[0] = %s" % (at, name))
    lines += ["}", "", "view_load(cells: ptr) {"]
    for k, (name, kind, init) in enumerate(vars_):
        at = "(cells + %d)" % (k * 8)
        if kind == "ptr":
            lines.append("    %s = (%s as ptr[])[0]" % (name, at))
        elif kind == "bool":
            lines.append("    %s = (%s as int[])[0] != 0" % (name, at))
        elif kind == "float":
            lines.append("    %s = (%s as float[])[0]" % (name, at))
        else:
            lines.append("    %s = (%s as int[])[0]" % (name, at))
    lines += ["}", "", "// Every variable as a frame with nothing made has it.", "view_reset() {"]
    for name, kind, init in vars_:
        lines.append("    %s = %s" % (name, init))
    lines += ["}", END]
    return "\n".join(lines) + "\n"

def main():
    text = open(MODULE).read()
    if BEGIN in text:
        head = text[:text.index(BEGIN)]
        tail = text[text.index(END) + len(END) + 1:]
        scan = head + tail
    else:
        head, tail, scan = text, "", text
    new = head + block(variables(scan)) + tail
    if "--check" in sys.argv:
        if new != text:
            print("gen_view_swap: %s is not what the module's variables make; run scripts/gen_view_swap.py" % MODULE)
            sys.exit(1)
        print("gen_view_swap: current")
        return
    open(MODULE, "w").write(new)
    print("gen_view_swap: wrote %d variables" % len(variables(scan)))

main()
